	/** Criteria that use information about the person: in that case they are told how to change it. */
	var PROFILING = [ 'CUSTOM_PARAM', 'SEGMENT', 'ADVERTISER_AUDIENCE' ];

	/**
	 * ⓘ button next to the ad label. It may end up inside the product page link or the element with Irios click
	 * tracking: it handles its click on its own node and stops propagation (no navigation and no ad click counted).
	 */
	function adInfoButton( response ) {
		var texts = cfg.adInfo || {};
		var button = document.createElement( 'span' );
		button.className = 'irios-ad-info';
		button.setAttribute( 'role', 'button' );
		button.setAttribute( 'tabindex', '0' );
		button.setAttribute( 'aria-label', texts.button || 'Information about this ad' );
		button.title = texts.button || '';
		button.style.cssText = 'display:inline-flex;vertical-align:middle;margin-left:0.3em;cursor:pointer;';
		button.innerHTML =
			'<svg width="1.1em" height="1.1em" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true">' +
			'<circle cx="12" cy="12" r="10"/><path d="M12 16v-4M12 8h.01" stroke-linecap="round"/></svg>';
		var open = function ( event ) {
			event.preventDefault();
			event.stopPropagation();
			showAdInfo( response );
		};
		button.addEventListener( 'click', open );
		button.addEventListener( 'keydown', function ( event ) {
			if ( event.key === 'Enter' || event.key === ' ' ) {
				open( event );
			}
		} );
		return button;
	}

	function showAdInfo( response ) {
		var texts = cfg.adInfo || {};
		var reasons = texts.reasons || {};
		var types = ( response && Array.isArray( response.targetingTypes ) ? response.targetingTypes : [] ).filter( function ( t, i, all ) {
			return reasons[ t ] && all.indexOf( t ) === i;
		} );
		var advertiser = ( response && response.advertiserName ) || texts.unknown || '';
		var esc = function ( text ) {
			var div = document.createElement( 'div' );
			div.textContent = text == null ? '' : String( text );
			return div.innerHTML;
		};
		var profiling = types.some( function ( t ) {
			return PROFILING.indexOf( t ) !== -1;
		} );
		var overlay = document.createElement( 'div' );
		overlay.className = 'irios-ad-info-overlay';
		overlay.style.cssText = 'position:fixed;inset:0;z-index:100000;background:rgba(0,0,0,.45);display:flex;align-items:center;justify-content:center;padding:16px;';
		overlay.innerHTML =
			'<div role="dialog" aria-modal="true" aria-labelledby="irios-ad-info-title" style="background:#fff;color:#222;max-width:480px;width:100%;border-radius:12px;padding:24px;position:relative;font-size:15px;line-height:1.55;box-shadow:0 10px 40px rgba(0,0,0,.25)">' +
			'<button type="button" data-close aria-label="' + esc( texts.ok ) + '" style="position:absolute;top:12px;right:12px;background:none;border:0;font-size:24px;line-height:1;cursor:pointer;color:#333">×</button>' +
			'<h2 id="irios-ad-info-title" style="margin:0 0 14px;font-size:20px">' + esc( texts.title ) + '</h2>' +
			'<p style="margin:0"><strong>' + esc( texts.why ) + '</strong><br>' + esc( texts.because ) + '</p>' +
			'<ul style="margin:4px 0 0;padding-left:1.2em">' +
			( types.length ? types.map( function ( t ) {
				return '<li>' + esc( reasons[ t ] ) + '</li>';
			} ).join( '' ) : '<li>' + esc( texts.noTargeting ) + '</li>' ) +
			'</ul>' +
			( profiling ? '<p style="margin:8px 0 0;opacity:.8">' + esc( texts.profiling ) + ' ' +
				( texts.privacyUrl ? '<a href="' + esc( texts.privacyUrl ) + '">' + esc( texts.privacy ) + '</a>' : esc( texts.privacy ) ) + '.</p>' : '' ) +
			'<p style="margin:16px 0 0"><strong>' + esc( texts.advertiser ) + '</strong></p>' +
			'<ul style="margin:4px 0 0;padding-left:1.2em"><li>' + esc( texts.name ) + ': <strong>' + esc( advertiser ) + '</strong></li>' +
			'<li>' + esc( texts.payer ) + ': <strong>' + esc( advertiser ) + '</strong></li></ul>' +
			'<div style="text-align:right;margin-top:20px"><button type="button" data-close class="button" style="cursor:pointer">' + esc( texts.ok ) + '</button></div>' +
			'</div>';
		var previous = document.activeElement;
		var close = function () {
			overlay.remove();
			document.removeEventListener( 'keydown', onKey, true );
			if ( previous && previous.focus ) {
				previous.focus();
			}
		};
		var onKey = function ( event ) {
			if ( event.key === 'Escape' ) {
				close();
			}
		};
		overlay.addEventListener( 'click', function ( event ) {
			if ( event.target === overlay || ( event.target.closest && event.target.closest( '[data-close]' ) ) ) {
				close();
			}
		} );
		document.addEventListener( 'keydown', onKey, true );
		document.body.appendChild( overlay );
		var ok = overlay.querySelector( '.button[data-close]' );
		if ( ok ) {
			ok.focus();
		}
	}

	function addLabel( item, response ) {
		var label = document.createElement( 'span' );
		label.className = 'irios-sponsored-label';
		label.textContent = cfg.sponsoredLabel || 'Sponsored';
		label.appendChild( adInfoButton( response ) );
		label.style.cssText = 'display:block;white-space:nowrap;font-size:0.75em;opacity:0.7;margin:0.25em 0;';
		var title = item.querySelector( TITLE_SELECTOR );
		if ( title && title.parentNode ) {
			var titleStyle = window.getComputedStyle( title );
			label.style.textAlign = titleStyle.textAlign || '';
			label.style.color = titleStyle.color || '';
			label.style.fontSize = Math.max( 11, parseFloat( titleStyle.fontSize ) * 0.75 ) + 'px';
			title.parentNode.insertBefore( label, title );
		} else {
			item.insertBefore( label, item.firstChild );
		}
	}

	/**
	 * Block themes: the "Add to cart" button works through the Interactivity API, which does not hydrate HTML inserted
	 * after page load. Its behaviour is replicated with the Store API and the mini-cart is notified with
	 * `wc-blocks_added_to_cart`. Not needed in classic themes: WooCommerce's AJAX listens on document.body.
	 */
	function wireBlockAddToCart( item ) {
		Array.prototype.forEach.call( item.querySelectorAll( 'button[data-product_id][data-wp-on--click]' ), function ( button ) {
			button.removeAttribute( 'data-wp-on--click' );
			button.addEventListener( 'click', function ( event ) {
				event.preventDefault();
				if ( button.disabled ) {
					return;
				}
				button.disabled = true;
				button.classList.add( 'loading' );
				storeApiAddItem( Number( button.getAttribute( 'data-product_id' ) ) )
					.then( function ( ok ) {
						button.classList.remove( 'loading' );
						button.disabled = false;
						if ( ok ) {
							button.classList.add( 'added' );
							document.body.dispatchEvent( new CustomEvent( 'wc-blocks_added_to_cart', { bubbles: true } ) );
						} else {
							window.location.href = button.closest( 'li' ).querySelector( 'a[href]' ).href; // product page
						}
					} );
			} );
		} );
	}

	function storeApiAddItem( productId ) {
		var base = cfg.storeApiUrl;
		return window
			.fetch( base + 'cart', { credentials: 'same-origin' } )
			.then( function ( r ) {
				return window.fetch( base + 'cart/add-item', {
					method: 'POST',
					credentials: 'same-origin',
					headers: { 'Content-Type': 'application/json', Nonce: r.headers.get( 'Nonce' ) || '' },
					body: JSON.stringify( { id: productId, quantity: 1 } ),
				} );
			} )
			.then( function ( r ) {
				return r.ok;
			} )
			.catch( function () {
				return false;
			} );
	}

	/**
	 * Load and viewability on the card; clicks only on the product page links. IriosTracker turns any click
	 * on a link into a navigation, and the add-to-cart button must keep working via AJAX.
	 */
	/** Tracks ad load, viewability and click; waits for the tracker (the ad may arrive first). */
	function trackAd( item, response ) {
		loadTracker()
			.then( function () {
				trackAdNow( item, response );
			} )
			.catch( function () {} );
	}

	function trackAdNow( item, response ) {
		var urls = nativeOf( response ).trackingUrls || {};
		if ( typeof window.IriosTracker !== 'function' ) {
			return;
		}
		// Documented fields (tracking-*) and, while the previous tracker is still deployed, the ones it read (*Urls).
		var user = adUser();
		var units = [
			Object.assign( {}, user, {
				element: item,
				'tracking-load': urls.loadTrackingUrl,
				'tracking-view': urls.viewTrackingUrl,
				loadUrls: urls.loadTrackingUrl,
				viewUrls: urls.viewTrackingUrl,
			} ),
		];
		if ( urls.clickTrackingUrl ) {
			Array.prototype.forEach.call( item.querySelectorAll( 'a[href]' ), function ( link ) {
				if ( ! link.matches( CART_LINK_SELECTOR ) ) {
					units.push( Object.assign( {}, user, {
						element: link,
						'tracking-click': urls.clickTrackingUrl,
						clickUrls: urls.clickTrackingUrl,
					} ) );
				}
			} );
		}
		try {
			new window.IriosTracker( units );
		} catch ( e ) {}
	}

	// ---- Banners ([irios_banner tag="…"], resolved in PHP to id and auth) ------------------------------------------------

	/** Controls placed after the grid (sorting, result count, pagination): the listing banner goes below them. */
	var LISTING_CONTROLS_SELECTOR =
		'.storefront-sorting, .woocommerce-ordering, .woocommerce-result-count, .woocommerce-pagination, nav.pagination, .pagi-nav';

		/** Product page tabs (description, additional information…): classic WooCommerce, custom themes and blocks. */
	var PRODUCT_TABS_SELECTOR = '.woocommerce-tabs, .detail-tabs, .wp-block-woocommerce-product-details';

	/**
	 * Places auto-positioned banners (printed hidden in the footer), centred: at the end of the category listing
	 * (after the grid and its sorting and pagination controls), or before the product page tabs (the
	 * description being the first). If there is no spot, the slot is removed.
	 */
	function placeBanners() {
		Array.prototype.forEach.call( document.querySelectorAll( '.irios-banner[data-irios-position]' ), function ( slot ) {
			var position = slot.getAttribute( 'data-irios-position' );
			slot.removeAttribute( 'data-irios-position' );
			var target = null;
			if ( position === 'category_after_products' ) {
				var grid = findGrid();
				var after = grid;
				while ( after && after.nextElementSibling && after.nextElementSibling.matches( LISTING_CONTROLS_SELECTOR ) ) {
					after = after.nextElementSibling;
				}
				target = after && { parent: after.parentNode, before: after.nextSibling };
			} else if ( position === 'product_before_description' ) {
				var tabs = Array.prototype.find.call( document.querySelectorAll( PRODUCT_TABS_SELECTOR ), function ( el ) {
					return ! el.closest( '.related, .upsells, .widget' );
				} );
				target = tabs && { parent: tabs.parentNode, before: tabs };
			}
			if ( ! target ) {
				warnTheme( 'banner-' + position, 'banner "' + ( slot.getAttribute( 'data-tag' ) || slot.getAttribute( 'data-ad-unit' ) ) +
					'": automatic position "' + position + '" not found on this page, banner not shown' );
				slot.parentNode.removeChild( slot );
				return;
			}
			target.parent.insertBefore( slot, target.before );
			slot.removeAttribute( 'hidden' );
			// Centred and spaced from the content (the creative may be narrower than the column).
			// As a column: the label («Patrocinado ⓘ») above the creative, both centred
			slot.style.display = 'flex';
			slot.style.flexDirection = 'column';
			slot.style.alignItems = 'center';
			slot.style.clear = 'both';
			slot.style.margin = '1.5em 0';
		} );
	}

	/**
	 * A single auction for all banner slots on the page (IriosLoader with all their ad units), with the visitor's uids
	 * and, on a category, its path as context. Each banner is rendered with render() called from a <script>
	 * inside its slot: the loader renders into the parent of document.currentScript.
	 */
	function renderBanners() {
		if ( ! cfg.bannersEnabled || cfg.bannersEnabled === '0' ) {
			return;
		}
		placeBanners();
		var slots = Array.prototype.filter.call( document.querySelectorAll( '.irios-banner[data-ad-unit]' ), function ( slot ) {
			return ! slot.hasAttribute( 'data-irios-rendered' );
		} );
		if ( ! slots.length ) {
			return;
		}
		var units = {};
		slots.forEach( function ( slot ) {
			slot.setAttribute( 'data-irios-rendered', '1' );
			units[ slot.getAttribute( 'data-ad-unit' ) ] = slot.getAttribute( 'data-auth' );
		} );
		var category = page.type === 'category' && page.value ? String( page.value ).split( ' > ' ) : [];
		var start = now();
		loadLoader()
			.then( function () {
				var loaderMs = now() - start;
				var auctionStart = now(); // the auction starts in the loader constructor
				window.__iriosWooBanners = new window.IriosLoader( Object.assign( adUser(), {
					category: category,
					adUnits: Object.keys( units ).map( function ( id ) {
						return { id: Number( id ), auth: units[ id ], type: 'banner' };
					} ),
				} ) );
				slots.forEach( function ( slot ) {
					var script = document.createElement( 'script' );
					script.text = 'window.__iriosWooBanners.render(' + Number( slot.getAttribute( 'data-ad-unit' ) ) + ');';
					debugBanner( slot, start, loaderMs, auctionStart );
					slot.appendChild( script );
					labelBanner( slot );
				} );
			} )
			.catch( function ( e ) {
				if ( window.console ) {
					window.console.warn( '[irios] banners not available', e );
				}
			} );
	}

	/**
	 * Banner label with its "About this ad" button, above the slot and only if Irios returns an ad. The
	 * creative is rendered by the loader (render(), in an iframe): getAds() is the same auction, with advertiser data.
	 */
	function labelBanner( slot ) {
		var loader = window.__iriosWooBanners;
		if ( ! loader || typeof loader.getAds !== 'function' ) {
			return;
		}
		loader.getAds( Number( slot.getAttribute( 'data-ad-unit' ) ) ).then( function ( ads ) {
			if ( ! ads || ! ads.length || slot.querySelector( '.irios-sponsored-label' ) ) {
				return;
			}
			var label = document.createElement( 'span' );
			label.className = 'irios-sponsored-label';
			label.textContent = cfg.sponsoredLabel || 'Sponsored';
			// Above the banner, at its top-right corner (same width as the rendered creative) and without wrapping
			// «Patrocinado ⓘ»
			label.style.cssText = 'display:block;white-space:nowrap;text-align:right;font-size:11px;opacity:0.7;margin:0 0 0.25em;box-sizing:border-box;align-self:center;max-width:100%;';
			var width = Number( ads[ 0 ].banner && ads[ 0 ].banner.width );
			if ( width ) {
				label.style.width = width + 'px'; // until the creative is rendered
			}
			label.appendChild( adInfoButton( ads[ 0 ] ) );
			slot.insertBefore( label, slot.firstChild );
			fitLabelToCreative( slot, label );
		}, function () {} );
	}

	/**
	 * The label takes the creative's actual width (the loader renders it later and the theme may scale it), so it sits at
	 * its top-right corner. Adjusted when the creative appears and whenever it is resized.
	 */
	function fitLabelToCreative( slot, label ) {
		var fit = function () {
			var creative = Array.prototype.find.call( slot.querySelectorAll( 'iframe, img, a, ins, div' ), function ( el ) {
				return ! label.contains( el ) && ! el.contains( label ) && el.getBoundingClientRect().width > 0;
			} );
			if ( ! creative ) {
				return false;
			}
			label.style.width = Math.round( creative.getBoundingClientRect().width ) + 'px';
			if ( window.ResizeObserver && ! label.__iriosResize ) {
				label.__iriosResize = new window.ResizeObserver( fit );
				label.__iriosResize.observe( creative );
			}
			return true;
		};
		if ( fit() || ! window.MutationObserver ) {
			return;
		}
		var observer = new window.MutationObserver( function () {
			if ( fit() ) {
				observer.disconnect();
			}
		} );
		observer.observe( slot, { childList: true, subtree: true } );
		window.setTimeout( function () {
			observer.disconnect();
		}, 10000 );
	}

	/** Debug mode: when the creative appears in the slot (the loader renders it without notifying). */
	function debugBanner( slot, start, loaderMs, auctionStart ) {
		if ( ! DEBUG || ! window.MutationObserver ) {
			return;
		}
		var id = slot.getAttribute( 'data-ad-unit' );
		var renderAt = auctionStart;
		var answeredAt = null;
		var loader = window.__iriosWooBanners;
		if ( loader && typeof loader.getAds === 'function' ) {
			// Same auction as render(): getAds() only tells when Irios has responded.
			loader.getAds( Number( id ) ).then( function ( ads ) {
				answeredAt = now();
				if ( ! ads || ! ads.length ) {
					observer.disconnect();
					window.clearTimeout( giveUp );
					debug( 'ad unit ' + id + ' · banner · Irios answered in ' + ms( answeredAt - renderAt ) + answerBreakdown( renderAt, answeredAt ) + ' with no ads' );
				}
			}, function () {} );
		}
		var observer = new window.MutationObserver( function () {
			var painted = Array.prototype.some.call( slot.querySelectorAll( '*' ), function ( el ) {
				return el.tagName !== 'SCRIPT' && ( el.tagName === 'IFRAME' || el.tagName === 'IMG' || el.offsetHeight > 0 );
			} );
			if ( painted ) {
				observer.disconnect();
				window.clearTimeout( giveUp );
				debug(
					'ad unit ' + id + ' · banner' + ( loaderMs > 5 ? ' · ' + loaderReady( loaderMs ) : '' ) +
						( answeredAt
							? ' · Irios answered in ' + ms( answeredAt - renderAt ) + answerBreakdown( renderAt, answeredAt ) + ' · rendered in ' + ms( now() - answeredAt )
							: ' · Irios answered and rendered in ' + ms( now() - renderAt ) ) +
						' · ad visible ' + ms( now() ) + ' after the page started loading'
				);
			}
		} );
		var giveUp = window.setTimeout( function () {
			observer.disconnect();
			debug( 'ad unit ' + id + ' · banner · no ad after ' + ms( now() - start ) );
		}, 10000 );
		observer.observe( slot, { childList: true, subtree: true, attributes: true } );
	}

	// ---- Theme live search (results while typing) ---------------------------------------------------------------------

	/**
	 * Many themes show results in a dropdown while the user types, and the customer
	 * goes to the product page without visiting the results page. Theme-independent:
	 *   - the dropdown is a list of links to product pages inside a search box (something with an "s" field);
	 *   - clicking a result stores the term and `search` is sent on the next page (sending it on click would be
	 *     lost when leaving the page);
	 *   - Sponsored Products are requested for the term (while typing, alongside the theme's search; one auction per
	 *     rendered list, never reusing earlier ads) and placed at their positions by cloning a list row; if the
	 *     list appears before the ads, it is briefly hidden (no layout jump).
	 */
	var live = { timer: null, prefetch: null, ads: {}, typedInput: null, watch: null, found: false };
	// Links that are not search results even though they sit in its area: the header mini-cart, for example.
	var NOT_RESULTS_SELECTOR = '[class*="mini-cart"], [class*="minicart"], .widget_shopping_cart, .woocommerce-mini-cart, .cart_list';
	var LIVE_HOLD_MS = 600; // max time the list stays hidden waiting for ads
	var SEARCH_INPUT = 'input[name="s"], input[type="search"]';
	// Live search suggestion containers that are not inside the form
	var LIVE_DROPDOWN_SELECTOR =
		'[class*="suggestion"], [class*="autocomplete"], [class*="search-result"], [class*="live-search"], [class*="ajax-search"]';

	/** With consent, once the customer's uids are available; without it, immediately (contextual ads). */
	function liveSearchEnabled() {
		return !! cfg.liveSearchAds && ( hasConsent() ? state.ready : true );
	}

	/** Live search auction for a term. Resolves to null when there are no ads. */
	function requestLiveAds( term ) {
		var timing = {};
		var pending = requestAds( cfg.liveSearchAds, term, [], 'data', timing ).catch( function () {
			return null;
		} );
		pending.timing = timing;
		return pending;
	}

	/**
	 * The term's auction is prefetched while the customer types (alongside the theme's AJAX search), only for the
	 * latest term; the list rendered for that term uses it and discards it.
	 */
	function prefetchLiveAds( term ) {
		live.ads = {};
		live.ads[ term ] = requestLiveAds( term );
	}

	/**
	 * Auction for the list being rendered: the prefetched one for that term if any (then discarded), or a new one.
	 * No caching: each rendered list is an auction, even if the term was searched before (Irios charges per event).
	 */
	function takeLiveAds( term ) {
		var pending = live.ads[ term ] || requestLiveAds( term );
		delete live.ads[ term ];
		return pending;
	}

	function isSearchInput( el ) {
		return el instanceof Element && el.matches( SEARCH_INPUT );
	}

	// Focusing the search box already downloads the loader; typing prefetches the term's auction.
	document.addEventListener(
		'focusin',
		function ( e ) {
			if ( isSearchInput( e.target ) && liveSearchEnabled() ) {
				loadLoader().catch( function () {} );
			}
		},
		true
	);
	document.addEventListener(
		'input',
		function ( e ) {
			if ( ! isSearchInput( e.target ) || ! liveSearchEnabled() ) {
				return;
			}
			// Only a search box the customer has typed in counts: some themes prefill it ("Search...", or the
			// term on the results page) and without this any nearby product list would look like its dropdown.
			live.typedInput = e.target;
			var term = e.target.value.trim();
			window.clearTimeout( live.prefetch );
			// Debug mode: if no dropdown with products appears after typing, warn (theme without live
			// search or with one the plugin does not recognise)
			window.clearTimeout( live.watch );
			if ( term.length >= 3 && ! live.found ) {
				live.watch = window.setTimeout( function () {
					if ( ! live.found ) {
						warnTheme( 'live-search', 'live search: no dropdown with product links found next to the search field, no ads shown there' );
					}
				}, 2500 );
			}
			if ( term ) {
				live.prefetch = window.setTimeout( function () {
					prefetchLiveAds( term );
				}, 250 );
			}
		},
		true
	);

	/** Hides the list without transition (it was just rendered) and shows it with a fade-in. */
	function holdList( container ) {
		container.style.transition = 'none';
		container.style.opacity = '0';
	}

	function releaseList( container ) {
		container.style.transition = 'opacity .15s ease-in';
		container.style.opacity = '';
	}

	function isProductLink( a ) {
		try {
			var u = new URL( a.href, window.location.href );
			return u.host === window.location.host && u.pathname.indexOf( cfg.productBase || '/product/' ) === 0;
		} catch ( e ) {
			return false;
		}
	}

	/** Search box an element belongs to: the closest form or "search" block with a search field. */
	function searchScope( el ) {
		var scope = el.closest( 'form, [class*="search"]' );
		while ( scope && scope !== document.body && scope.tagName !== 'MAIN' ) {
			var input = scope.querySelector( 'input[name="s"], input[type="search"]' );
			if ( input ) {
				return { el: scope, input: input };
			}
			scope = scope.parentElement && scope.parentElement.closest( 'form, [class*="search"]' );
		}
		// Dropdowns the search box renders outside its form (e.g. FiboSearch, at the end of body): attributed to the
		// search box the customer just typed in
		var dropdown = el.closest( LIVE_DROPDOWN_SELECTOR );
		if ( dropdown && live.typedInput && live.typedInput.value.trim() ) {
			return { el: dropdown, input: live.typedInput };
		}
		return null;
	}

	document.addEventListener(
		'click',
		function ( e ) {
			var a = e.target instanceof Element ? e.target.closest( 'a[href]' ) : null;
			var scope = a && isProductLink( a ) ? searchScope( a ) : null;
			var term = scope ? scope.input.value.trim() : '';
			if ( term && hasConsent() ) {
				try {
					window.sessionStorage.setItem( PENDING_SEARCH_KEY, term );
				} catch ( err ) {}
			}
		},
		true
	);

	function scanLiveSearch() {
		if ( ! liveSearchEnabled() ) {
			return;
		}
		if ( ! live.typedInput ) {
			return; // the customer has not typed in any search box yet
		}
		var links = Array.prototype.filter.call( document.querySelectorAll( 'a[href]' ), function ( a ) {
			return isProductLink( a ) && a.offsetParent !== null && ! a.closest( '.irios-sponsored, [data-irios-ads]' ) && ! a.closest( NOT_RESULTS_SELECTOR );
		} );
		var scope = null;
		var inScope = links.filter( function ( a ) {
			var s2 = searchScope( a );
			if ( s2 && s2.input === live.typedInput && s2.input.value.trim() && ( ! scope || scope.el === s2.el ) ) {
				scope = s2;
				return true;
			}
			return false;
		} );
		if ( ! scope || ! inScope.length ) {
			return; // no visible dropdown
		}
		// List: common container of the results (or that of the only row).
		var container = inScope[ 0 ].parentElement;
		var other = inScope.find( function ( a ) {
			return normalizeUrl( a.href ) !== normalizeUrl( inScope[ 0 ].href );
		} );
		if ( other ) {
			while ( container && ! container.contains( other ) ) {
				container = container.parentElement;
			}
		} else {
			var node = inScope[ 0 ];
			while ( node.parentElement && node.parentElement.children.length < 2 && node.parentElement !== scope.el ) {
				node = node.parentElement;
			}
			container = node.parentElement;
		}
		var term = scope.input.value.trim();
		var template = container && itemOf( container, inScope[ 0 ] );
		// Already done for this term and this list. If the theme re-rendered the list (its AJAX response arrives
		// after the customer keeps typing), the rows are different and it is done again.
		if ( ! container || ( container.getAttribute( 'data-irios-live-term' ) === term && container.__iriosRow && container.__iriosRow.parentElement === container ) ) {
			return;
		}
		container.setAttribute( 'data-irios-live-term', term );
		live.found = true;
		Array.prototype.forEach.call( container.querySelectorAll( ':scope > .irios-sponsored' ), function ( el ) {
			el.remove();
		} );
		Array.prototype.forEach.call( container.querySelectorAll( ':scope > [data-irios-hidden]' ), function ( el ) {
			el.style.display = '';
			el.removeAttribute( 'data-irios-hidden' );
		} );

		container.__iriosRow = template;
		var templateUrl = normalizeUrl( inScope[ 0 ].href );
		var titleText = resultTitle( template, templateUrl );
		// If the auction already finished, then() runs before painting and the list never gets hidden.
		holdList( container );
		var hold = window.setTimeout( function () {
			releaseList( container );
		}, LIVE_HOLD_MS );
		var pending = takeLiveAds( term );
		pending
			.then( function ( result ) {
				window.clearTimeout( hold );
				var where = 'live search ' + JSON.stringify( term );
				if ( ! result ) {
					debugTiming( unitsLabel( cfg.liveSearchAds.units ), where, pending.timing, false );
					return; // no ads
				}
				if ( container.getAttribute( 'data-irios-live-term' ) !== term || container.__iriosRow !== template || ! container.isConnected ) {
					return; // the customer kept typing: it goes into the new list
				}
				var byId = {};
				result.cards.forEach( function ( card ) {
					byId[ card.id ] = card;
				} );
				// Each ad at its list position (1 = first row), after hiding rows of the same product.
				var items = [];
				result.placements.forEach( function ( p ) {
					var card = byId[ String( nativeOf( p.response ).product.id ) ];
					if ( ! card ) {
						return;
					}
					items.push( { item: cloneResult( template, templateUrl, titleText, card ), placement: p } );
					Array.prototype.forEach.call( container.children, function ( row ) {
						var link = row.querySelector( 'a[href]' );
						if ( link && ! row.classList.contains( 'irios-sponsored' ) && Number( card.productId ) && isSameProduct( link.href, card ) ) {
							row.style.display = 'none';
							row.setAttribute( 'data-irios-hidden', '1' );
						}
					} );
				} );
				items.forEach( function ( entry ) {
					placeAt( container, entry.item, entry.placement.position );
					addLabel( entry.item, entry.placement.response );
					trackAd( entry.item, entry.placement.response );
				} );
				debugTiming( unitsLabel( cfg.liveSearchAds.units ), where, pending.timing, true );
			} )
			.catch( function () {} )
			.then( function () {
				releaseList( container );
			} );
	}

	/** The row links to the same product as the ad (same product page, ignoring the selected variation). */
	function isSameProduct( href, card ) {
		return normalizeUrl( href ) === normalizeUrl( card.link );
	}

	if ( window.MutationObserver ) {
		new window.MutationObserver( function () {
			window.clearTimeout( live.timer );
			live.timer = window.setTimeout( scanLiveSearch, 50 ); // batches changes from the same render
		} ).observe( document.body, { childList: true, subtree: true } );
	}

