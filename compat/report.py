"""Builds the compatibility table from compat/results/*.json (written by compat/compat.spec.mjs, one per combination)
and compat/manual/*.json (same format):
compat/RESULTS.md with details, and the table in README.md between <!-- compat:start --> and <!-- compat:end -->."""
import json
import re
import sys
from datetime import date
from pathlib import Path

CHECKS = [
    ("search_grid", "Sponsored in search"),
    ("ad_label_info", "Label + “About this ad”"),
    ("ad_card_layout", "Card like the results"),
    ("add_to_cart", "Add to cart on the ad"),
    ("live_search", "Live search"),
    ("banner_category", "Category banner"),
    ("banner_product", "Product page banner"),
]
ICON = {"pass": "✅", "fail": "❌", "na": "—"}
LEGEND = "✅ works · ❌ fails · — not applicable, e.g. the theme has no live search."
# Display names of the plugins in compat/themes.txt
PLUGINS = {"ajax-search-for-woocommerce": "FiboSearch", "yith-woocommerce-ajax-search": "YITH WooCommerce Ajax Search"}

results_dir, out, readme = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]) if len(sys.argv) > 3 else None
# compat/manual/*.json: themes that run.sh cannot install (premium); compat/results wins for the same combination
by_combo = {}
for f in sorted((results_dir.parent / "manual").glob("*.json")) + sorted(results_dir.glob("*.json")):
    r = json.loads(f.read_text())
    by_combo[r["combo"]] = r
rows = sorted(by_combo.values(), key=lambda r: ("+" in r["combo"], r["combo"]))
# Date of the newest result, not of this report: regenerating the table does not re-test the themes
files = list((results_dir.parent / "manual").glob("*.json")) + list(results_dir.glob("*.json"))
tested = date.fromtimestamp(max(f.stat().st_mtime for f in files)).isoformat() if files else date.today().isoformat()


def name(combo):
    theme, _, plugin = combo.partition("+")
    return f"`{theme}` + {PLUGINS.get(plugin, plugin)} plugin" if plugin else f"`{theme}`"


table = [
    "| Theme | " + " | ".join(label for _, label in CHECKS) + " |",
    "|---|" + "---|" * len(CHECKS),
] + [
    f"| {name(r['combo'])} | " + " | ".join(ICON.get(r.get("checks", {}).get(key), "❌") for key, _ in CHECKS) + " |"
    for r in rows
]


def notes_of(r):
    # The "no dropdown" warning is expected on a theme without live search
    warnings = [
        w for w in r.get("warnings", [])
        if not (r.get("checks", {}).get("live_search") == "na" and "live search:" in w)
    ]
    return warnings + r.get("errors", [])


lines = [
    "# WordPress theme compatibility",
    "",
    f"Generated by `compat/run.sh` on {tested}, against the IRIOS Media simulator (`dev/irios-stub.php`). "
    + LEGEND,
    "",
    *table,
]
notes = [(r, notes_of(r)) for r in rows if notes_of(r)]
if notes:
    lines += ["", "## Warnings and errors", ""]
    for r, msgs in notes:
        lines += [f"- {name(r['combo'])}: {msg}" for msg in msgs]
out.write_text("\n".join(lines) + "\n")
print(out)

if readme:
    block = "\n".join(
        ["<!-- compat:start -->", f"Tested on {tested}. {LEGEND}", "", *table, "<!-- compat:end -->"]
    )
    text = readme.read_text()
    new = re.sub(r"<!-- compat:start -->.*?<!-- compat:end -->", lambda _: block, text, flags=re.S)
    if new == text and "<!-- compat:start -->" not in text:
        sys.exit("README.md has no <!-- compat:start --> marker")
    readme.write_text(new)
    print(readme)
